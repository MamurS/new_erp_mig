/*
 * `supabase/seed.sql` from the deterministic demo database (packages/seed, BACKEND_SPEC §3 «seed.sql
 * (генерируется)»). Rows keep their storage order in `_pos`.
 *
 * DEV/CI ONLY: personal data that the API encrypts (PINFL, phone, free medical texts) is sealed here with
 * AES-256-GCM under the published development key (version 1, store/piiAes.ts) with IVs derived from the value
 * (so the file is stable), and the search HMAC under the development HMAC key; no personal data is in the file
 * in clear. A deployment without `PII_KEYS` (development, CI) reads it with the same key; production refuses the
 * development keys, so a real environment never loads this seed.
 *
 * The Supabase Auth users of the demo accounts follow the data (authSeed.ts).
 */
