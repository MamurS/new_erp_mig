function factSql(f: FactFn): string {
  const name = f.sig.replace(/\(.*\)/, '');
  const types = f.sig
    .replace(/^.*\(|\)$/g, '')
    .split(',')
    .map((x) => x.trim().split(/\s+/).slice(1).join(' '))
    .filter(Boolean)
    .join(', ');
  return `create or replace function app.${f.sig} returns ${f.returns}
  language plpgsql ${f.volatility ?? 'stable'} security definer set search_path = ''
as $$
begin
  if not app.active() or not coalesce((${f.gate}), false) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  ${f.body}
end $$;
comment on function app.${name}(${types}) is ${lit(f.comment)};
revoke execute on function app.${name}(${types}) from public;
grant execute on function app.${name}(${types}) to authenticated, service_role;
`;
}

/** The migration with every fact function. */
export function factsMigration(): string {
  return `${HEADER}
${FACT_FUNCTIONS.map(factSql).join('\n')}`;
}
