const HEADER = `-- Narrow facts (docs/PRIVILEGED_AUDIT.md): counts, codes and anonymous figures of rows the caller's RLS hides; side effects in another party's feed.
-- Generated by scripts/gen-schema.mjs from packages/domain/src/store/sql/facts.ts. Do not edit by hand:
-- change the TypeScript source and run \`node scripts/gen-schema.mjs\`.
`;

/** `YYYY-MM-DDTHH:mm:ss+05:00`, as the repositories read a `ts` column. */
export const tsText = (col: string) => `to_char(${col} at time zone app.tz(), 'YYYY-MM-DD"T"HH24:MI:SS"+05:00"')`;

/** The row `key = value` of a table is visible to the caller by the table's SELECT policy (evaluated by the definer). */
export function visible(collection: string, keyColumn: string, value: string): string {
  const t = TABLES.find((x) => x.collection === collection);
  if (!t) throw new Error(`No table ${collection}`);
  const e = grantExpression(t.access.select);
  if (!e) return 'false';
  return `exists (select 1 from public.${t.table} v where v.${keyColumn} = ${value} and (${e.replace(/\n\s*/g, ' ')}))`;
}

interface FactFn {
  /** Signature inside schema `app`, e.g. `fact_client_insured_count(p_client uuid)`. */
  sig: string;
  returns: string;
  /** PL/pgSQL condition the caller must meet (besides app.active()). */
  gate: string;
  /** The body after the gate: `return …;` statements. */
  body: string;
  comment: string;
  volatility?: 'stable' | 'volatile';
}

