/*
 * The narrow facts of store/facts.ts as SQL functions of schema `app` (docs/PRIVILEGED_AUDIT.md). Every function:
 * - is SECURITY DEFINER with `search_path = ''` (it reads rows the caller's RLS hides);
 * - checks `app.active()` and the permission or the scope itself, and raises 42501 otherwise;
 * - returns only the value the service needs (a count, a code, anonymous figures in storage order);
 * - may be executed by `authenticated` (the API's system repositories compute the same in TypeScript).
 * Its twin in TypeScript (`genericFacts`) must return exactly the same: the conformance test compares them.
 */
