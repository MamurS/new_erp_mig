function tableDdl(t: TableSpec): string {
  const cols = physicalColumns(t);
  const lines: string[] = [];
  if (t.key === null) lines.push(`${LOG_ID} uuid primary key default gen_random_uuid()`);
  const key = t.key === null ? null : snake(t.key);
  for (const c of cols) {
    let l = `${qi(c.name)} ${c.sqlType}`;
    if (c.name === key) l += ' primary key';
    else if (c.notNull) l += ' not null';
    if (c.unique) l += ' unique';
    if (c.check) l += ` check (${c.check})`;
    lines.push(l);
  }
  lines.push(`_pos bigint not null default nextval('app.pos_seq')`);
  lines.push(`_created_at timestamptz not null default now()`);
  lines.push(`_updated_at timestamptz not null default now()`);
  lines.push(`_created_by uuid default app.uid()`);
  const out = [`create table public.${t.table} (\n  ${lines.join(',\n  ')}\n);`];
  out.push(`comment on table public.${t.table} is ${lit(`Collection ${t.collection} (${t.kind}).`)};`);
  out.push(`create trigger ${t.table}_stamp before insert or update on public.${t.table} for each row execute function app.stamp();`);
  out.push(`create index ${t.table}__pos_idx on public.${t.table} (_pos);`);
  const seen = new Set<string>();
  for (const ix of t.indexes) {
    if (typeof ix === 'object' && 'trgm' in ix) {
      const c = indexColumn(t, ix.trgm);
      out.push(`create index ${t.table}_${c}_trgm_idx on public.${t.table} using gin (${qi(c)} extensions.gin_trgm_ops);`);
      continue;
    }
    const fields = typeof ix === 'string' ? [ix] : 'unique' in ix ? ix.unique : (ix as readonly string[]);
    const cs = fields.map((f) => indexColumn(t, f));
    const name = `${t.table}_${cs.join('_')}_idx`;
    if (seen.has(name)) throw new Error(`Duplicate index ${name}`);
    seen.add(name);
    const unique = typeof ix === 'object' && 'unique' in ix ? 'unique ' : '';
    out.push(`create ${unique}index ${name} on public.${t.table} (${cs.map(qi).join(', ')});`);
  }
  return out.join('\n');
}

function foreignKeys(t: TableSpec): string[] {
  return physicalColumns(t)
    .filter((c) => c.references)
    .map((c) => `alter table public.${t.table} add constraint ${t.table}_${c.name}_fkey foreign key (${qi(c.name)}) references ${c.references} deferrable initially deferred;`);
}

function schema(): string {
  const parts = [HEADER('Tables of every collection (BACKEND_SPEC §5): keys, NOT NULL, CHECK for enums, deferrable foreign keys, indexes.')];
  for (const t of TABLES) parts.push(tableDdl(t));
  parts.push(`-- Foreign keys (deferrable: rows of one change may arrive in any order within a transaction).\n${TABLES.flatMap(foreignKeys).join('\n')}`);
  parts.push('-- Document number sequences (repo `seq`): next() = nextval().');
  for (const [name, coll] of Object.entries(SEQUENCES)) parts.push(`create sequence public.${sequenceName(name as keyof typeof SEQUENCES)}; -- ${coll}`);
  parts.push(`-- Singletons hold one row.\nalter table public.ai_settings add constraint ai_settings_one_row check (id = 1);\nalter table public.integrations_seed add constraint integrations_seed_one_row check (id = 1);`);
  return parts.join('\n\n') + '\n';
}

function insuredView(): string {
  const ins = TABLES.find((t) => t.collection === 'insured')!;
  const listed = readableColumns(ins).filter((c) => !['birth_date', 'email'].includes(c));
  return `-- Lists of insured persons: no ciphertexts, the birth date and email masked (security_invoker: RLS of the caller applies).
create view public.insured_masked with (security_invoker = true) as
  select ${listed.map(qi).join(', ')},
    '••.••.' || to_char(birth_date, 'YYYY') as birth_date_masked,
    app.mask_email(email) as email_masked
  from public.insured;
comment on view public.insured_masked is 'Masked list view of insured persons (BACKEND_SPEC §6): the API uses it for lists.';`;
}

