// 5. audit log: append-only with a hash chain (BACKEND_SPEC §9)
// ------------------------------------------------------------------------------------------------
function audit(): string {
  return `${HEADER('Audit log: append-only, written only through app.audit(), hash chain and its verification (BACKEND_SPEC §9).')}
alter table public.audit_log
  add column chain_seq bigint,
  add column prev_hash bytea,
  add column hash bytea;
create unique index audit_log_chain_seq_idx on public.audit_log (chain_seq);
comment on column public.audit_log.hash is 'sha256(hex(prev_hash) | canonical entry): the chain of app.verify_audit_chain().';

-- Canonical text of an entry (the hashed fields; NULL is an empty string).
create or replace function app.audit_canonical(e public.audit_log) returns text
  language sql immutable set search_path = ''
as $$
  select concat_ws('|', e.id::text, to_char(e."at" at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'), e.actor_id::text,
    e.actor_name, e.actor_role, e.action, e.target_type, coalesce(e.target_id, ''), coalesce(e.target_label, ''),
    coalesce(e.reason, ''), coalesce(e.assistance_id::text, ''))
$$;

-- Links every new entry to the previous one. Entries are serialized by an advisory lock; the API works in
-- READ COMMITTED, so the statement after the lock sees the last committed entry.
create or replace function app.audit_chain() returns trigger
  language plpgsql security definer set search_path = ''
as $$
declare
  v_prev public.audit_log;
begin
  perform pg_advisory_xact_lock(hashtext('app.audit_chain'));
  select * into v_prev from public.audit_log order by chain_seq desc limit 1;
  new.chain_seq := coalesce(v_prev.chain_seq, 0) + 1;
  new.prev_hash := v_prev.hash;
  new.hash := extensions.digest(coalesce(encode(v_prev.hash, 'hex'), '') || '|' || app.audit_canonical(new), 'sha256');
  return new;
end $$;
create trigger audit_log_chain before insert on public.audit_log for each row execute function app.audit_chain();

-- Append-only, also for the table owner and the service role: no UPDATE, DELETE or TRUNCATE.
create or replace function app.audit_immutable() returns trigger
  language plpgsql set search_path = ''
as $$
begin
  raise exception 'audit_log is append-only' using errcode = '42501';
end $$;
create trigger audit_log_no_update before update or delete on public.audit_log for each row execute function app.audit_immutable();
create trigger audit_log_no_truncate before truncate on public.audit_log for each statement execute function app.audit_immutable();
revoke insert, update, delete, truncate on public.audit_log from authenticated, anon, service_role;

-- The only way to write an entry. For a signed-in user the actor is taken from the claims (cannot be forged);
-- the service role (system jobs, sign-in events) passes the actor explicitly.
create or replace function app.audit(
  p_action text,
  p_target_type text,
  p_target_id text default null,
  p_target_label text default null,
  p_reason text default null,
  p_assistance_id uuid default null,
  p_actor_name text default null,
  p_actor_id uuid default null,
  p_actor_role text default null,
  p_at timestamptz default now(),
  p_id uuid default gen_random_uuid()
) returns uuid
  language plpgsql volatile security definer set search_path = ''
as $$
declare
  v_actor uuid := p_actor_id;
  v_role text := p_actor_role;
begin
  if app.uid() is not null then
    if not app.active() then
      raise exception 'not signed in' using errcode = '42501';
    end if;
    v_actor := app.uid();
    v_role := app.role();
  elsif coalesce(current_setting('role', true), 'none') in ('authenticated', 'anon') then
    raise exception 'audit entries are written by a signed-in user or the system' using errcode = '42501';
  end if;
  if v_actor is null or v_role is null then
    raise exception 'audit actor is required' using errcode = '22023';
  end if;
  insert into public.audit_log (id, "at", actor_id, actor_name, actor_role, action, target_type, target_id, target_label, reason, assistance_id)
  values (p_id, p_at, v_actor, coalesce(p_actor_name, ''), v_role, p_action, p_target_type, p_target_id, p_target_label, p_reason, p_assistance_id);
  return p_id;
end $$;
comment on function app.audit is 'Writes an audit entry (BACKEND_SPEC §9): the only INSERT path for authenticated.';

-- Recomputes the chain in order; ok = false with the first broken entry.
create or replace function app.verify_audit_chain() returns table (ok boolean, checked bigint, first_broken uuid)
  language plpgsql stable security definer set search_path = ''
as $$
declare
  r public.audit_log;
  v_prev bytea := null;
  v_n bigint := 0;
begin
  for r in select * from public.audit_log order by chain_seq loop
    v_n := v_n + 1;
    if r.prev_hash is distinct from v_prev
      or r.hash is distinct from extensions.digest(coalesce(encode(v_prev, 'hex'), '') || '|' || app.audit_canonical(r), 'sha256') then
      return query select false, v_n, r.id;
      return;
    end if;
    v_prev := r.hash;
  end loop;
  return query select true, v_n, null::uuid;
end $$;
comment on function app.verify_audit_chain is 'Verifies the audit hash chain (daily by pg_cron).';

revoke execute on all functions in schema app from public;
grant execute on all functions in schema app to authenticated, service_role;
revoke execute on function app.verify_audit_chain() from authenticated;
revoke execute on function app.audit_chain() from authenticated;
revoke execute on function app.audit_immutable() from authenticated;
`;
}

