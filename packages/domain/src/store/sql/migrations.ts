// 3. scope helpers (they read tables: SECURITY DEFINER, no RLS recursion) and reveal
// ------------------------------------------------------------------------------------------------
function scopes(): string {
  const def = (sig: string, returns: string, body: string, comment: string, volatility = 'stable') =>
    `create or replace function app.${sig} returns ${returns}\n  language sql ${volatility} security definer set search_path = ''\nas $$\n  ${body}\n$$;\ncomment on function app.${sig.replace(/\(.*\)/, '')} is ${lit(comment)};\n`;
  const reveal: string[] = [];
  for (const t of TABLES) {
    const r = REVEAL[t.collection];
    const fields = Object.entries(t.columns).filter(([, c]) => c.pii === 'encrypt+hmac');
    if (!fields.length) continue;
    if (!r) throw new Error(`No REVEAL rule for ${t.collection}`);
    const visible = grantExpression(t.access.select) ?? 'false';
    const allowed = `(${cached(r.self)}) or ((select app.can_any(array[${r.actions.map(lit).join(', ')}]::text[])) and ${visible})`;
    for (const [f] of fields) {
      const col = snake(f);
      reveal.push(`  if p_table = ${lit(t.table)} and p_field = ${lit(col)} then
    select r.${col}_enc, r.${col}_key_ver into v_enc, v_ver from public.${t.table} r
      where r.${keyColumn(t)}::text = p_id and (${allowed.replace(/\n\s*/g, ' ')});
  end if;`);
    }
  }
  return `${HEADER('Scope helpers of the RLS policies (BACKEND_SPEC §6): «own» rows of HR, the insured, clinics and assistance companies.')}
${def('my_policy_id()', 'uuid', 'select i.policy_id from public.insured i where i.id = app.insured_id()', 'Policy of the signed-in insured person.')}
${def('my_client_id()', 'uuid', 'select i.client_id from public.insured i where i.id = app.insured_id()', 'Client company of the signed-in insured person.')}
${def(
  'my_family_ids()',
  'uuid[]',
  `select coalesce(array_agg(distinct x), '{}') from (
    select app.insured_id() as x
    union all select i.id from public.insured i where i.principal_id = app.insured_id()
    union all select i.principal_id from public.insured i where i.id = app.insured_id() and i.principal_id is not null
  ) s where x is not null`,
  'The insured person, the family under them and their employee: names of the family screen.',
)}
${def(
  'my_person_ids()',
  'uuid[]',
  `select coalesce(array_agg(distinct x), '{}') from (
    select app.insured_id() as x
    union all select i.id from public.insured i where i.principal_id = app.insured_id() and i.relation = 'child'
    union all select c.owner_id from public.family_consents c
      join public.insured o on o.id = c.owner_id
      where c.viewer_id = app.insured_id() and c.revoked_at is null and o.principal_id = app.insured_id()
  ) s where x is not null`,
  'Persons whose claims and appointments the insured person sees: self, children, adults of the family with consent (FAMILY_SPEC).',
)}
${def(
  'clinic_patient_ids()',
  'uuid[]',
  "select coalesce(array_agg(distinct v.insured_id), '{}') from public.visits v where v.clinic_id = app.clinic_id() and v.expires_at > now()",
  'Patients of the clinic with an open visit (CLINIC_SPEC: access only through a visit).',
)}
${def(
  'assist_covers(p_policy uuid, p_day date)',
  'boolean',
  `select exists (select 1 from public.assignments a
    where a.policy_id = p_policy and a.assistance_id = app.assistance_id()
      and a."from" <= p_day and (a."to" is null or p_day <= a."to"))`,
  'The policy is assigned to the user’s assistance company on the date (ASSISTANCE_SPEC §3).',
)}
${def(
  'assist_covers_insured(p_insured uuid, p_day date)',
  'boolean',
  'select app.assist_covers((select i.policy_id from public.insured i where i.id = p_insured), p_day)',
  'The person’s policy is assigned to the user’s assistance company on the date.',
)}
${def('client_of_contract(p_contract uuid)', 'uuid', 'select c.client_id from public.contracts c where c.id = p_contract', 'Client of a contract (HR scope of appendices, change requests, endorsements).')}
${def(
  'registry_has_payer(p_lines jsonb, p_payer uuid)',
  'boolean',
  "select p_payer is not null and exists (select 1 from jsonb_array_elements(coalesce(p_lines, '[]'::jsonb)) l where l ->> 'payer' = p_payer::text)",
  'A registry has lines paid by the assistance company.',
  'immutable',
)}
${def(
  'mask_email(p_email text)',
  'text',
  "select case when p_email is null or p_email = '' then p_email else left(split_part(p_email, '@', 1), 1) || '•••@' || split_part(p_email, '@', 2) end",
  'a•••@company.uz (the same mask as packages/domain/src/lib/mask.ts).',
  'immutable',
)}
-- The full value of PINFL or phone (ciphertext and key version; the API decrypts) for a role allowed to see
-- it, written to the audit log. The only way for \`authenticated\` to read *_enc of identity data.
create or replace function app.reveal(p_table text, p_id text, p_field text, p_reason text, p_actor_name text default null)
  returns table (enc bytea, key_ver smallint)
  language plpgsql volatile security definer set search_path = ''
as $$
declare
  v_enc bytea;
  v_ver smallint;
begin
  if not app.active() then
    raise exception 'not signed in' using errcode = '42501';
  end if;
  if coalesce(btrim(p_reason), '') = '' then
    raise exception 'a reason is required' using errcode = '22023';
  end if;
${reveal.join('\n')}
  if v_enc is null then
    raise exception 'not found' using errcode = 'P0002';
  end if;
  perform app.audit('reveal_pii', 'insured', p_id, null, p_field || ': ' || p_reason, app.assistance_id(), p_actor_name);
  return query select v_enc, v_ver;
end $$;
comment on function app.reveal(text, text, text, text, text) is 'Ciphertext of an identity field for an allowed role, audited (BACKEND_SPEC §5).';

${insuredView()}

revoke execute on all functions in schema app from public;
grant execute on all functions in schema app to authenticated, service_role;
`;
}

