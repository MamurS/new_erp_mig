// 4. RLS and privileges
// ------------------------------------------------------------------------------------------------
const PRIV: Record<(typeof OPS)[number], string> = { select: 'select', insert: 'insert', update: 'update', delete: 'delete' };

function rls(): string {
  const parts = [
    HEADER('Row level security on every table of `public` (BACKEND_SPEC §6), generated from the access rules of schema.ts and the permissions matrix.'),
    `-- Nobody but the API reaches the database; the anon role gets nothing.
revoke all on all tables in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
alter default privileges in schema public revoke all on tables from anon, authenticated;`,
  ];
  for (const t of TABLES) {
    const out = [`-- ${t.table}: ${t.access.note}`, `alter table public.${t.table} enable row level security;`];
    const privs: string[] = [];
    for (const op of OPS) {
      const e = grantExpression(t.access[op]);
      if (e === null) continue;
      privs.push(PRIV[op]);
      const name = `${t.table}_${op}`;
      if (op === 'select' || op === 'delete') out.push(`create policy ${name} on public.${t.table} for ${op} to authenticated\n  using (${e});`);
      else if (op === 'insert') out.push(`create policy ${name} on public.${t.table} for insert to authenticated\n  with check (${e});`);
      else out.push(`create policy ${name} on public.${t.table} for update to authenticated\n  using (${e})\n  with check (${e});`);
    }
    if (privs.length) {
      const nonSelect = privs.filter((p) => p !== 'select');
      if (privs.includes('select')) {
        if (hasSecrets(t)) out.push(`grant select (${readableColumns(t).map(qi).join(', ')}) on public.${t.table} to authenticated;`);
        else nonSelect.unshift('select');
      }
      if (nonSelect.length) out.push(`grant ${nonSelect.join(', ')} on public.${t.table} to authenticated;`);
    }
    parts.push(out.join('\n'));
  }
  parts.push(`grant select on public.insured_masked to authenticated;
grant usage on all sequences in schema public to authenticated;`);
  return parts.join('\n\n') + '\n';
}

