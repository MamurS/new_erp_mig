#!/usr/bin/env node
/*
 * Regenerates src/features/kp/templates/gold.ts from the vendored GOLD brochure generator.
 * Run after updating vendor/gold-brochure-generator/templates.js:
 *
 *   node scripts/import-gold-templates.mjs
 *
 * Then update the pinned hash in src/features/kp/templates/gold.test.ts on purpose.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'vendor/gold-brochure-generator/templates.js');
const out = resolve(root, 'src/features/kp/templates/gold.ts');

const VERSION = 'GOLD 09/26';
const LANGS = ['ru', 'en'];
const VARIANTS = ['white', 'grey', 'black'];
const PAGES = 16;

const raw = readFileSync(src, 'utf8').trim();
const prefix = 'window.GOLD_TEMPLATES=';
if (!raw.startsWith(prefix)) throw new Error(`Unexpected templates.js format: missing "${prefix}"`);
// The file is a single JSON literal assigned to a global; parse it as data, never evaluate it.
const templates = JSON.parse(raw.slice(prefix.length).replace(/;\s*$/, ''));

const expectedKeys = LANGS.flatMap((l) => VARIANTS.map((v) => `${l}-${v}`)).sort();
const keys = Object.keys(templates).sort();
if (JSON.stringify(keys) !== JSON.stringify(expectedKeys)) throw new Error(`Unexpected template keys: ${keys.join(', ')}`);

for (const key of keys) {
  const pages = templates[key];
  if (!Array.isArray(pages) || pages.length !== PAGES) throw new Error(`${key}: expected ${PAGES} pages`);
  for (const [i, page] of pages.entries()) {
    if (typeof page !== 'string') throw new Error(`${key}[${i}]: page is not a string`);
    if (/<script/i.test(page)) throw new Error(`${key}[${i}]: <script> is not allowed`);
    if (/\son[a-z]+\s*=/i.test(page)) throw new Error(`${key}[${i}]: inline event handlers are not allowed`);
    if (/javascript:/i.test(page)) throw new Error(`${key}[${i}]: javascript: URLs are not allowed`);
  }
}

const ordered = Object.fromEntries(expectedKeys.map((k) => [k, templates[k]]));
const body = `/*
 * GENERATED by scripts/import-gold-templates.mjs from vendor/gold-brochure-generator/templates.js.
 * Do not edit by hand: the brochure texts are approved. The content hash is pinned in gold.test.ts.
 */
import type { KpLang, KpVariant } from '@/shared/types';

export const GOLD_TEMPLATE_VERSION = ${JSON.stringify(VERSION)};

export const GOLD_TEMPLATES: Readonly<Record<\`\${KpLang}-\${KpVariant}\`, readonly string[]>> = ${JSON.stringify(ordered, null, 2)};
`;
writeFileSync(out, body);
console.log(`Wrote ${out} (${keys.length} variants × ${PAGES} pages)`);
